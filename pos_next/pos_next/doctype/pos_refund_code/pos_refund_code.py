import frappe
from frappe import _
from frappe.model.document import Document
from frappe.utils import today

from pos_next.services.confirmation_code import generate_codes_for, prepare_code

CODE_DOCTYPE = "POS Refund Code"
# not translated: marks codes made by generate_daily_code so a new one can disable them
DAILY_NOTE_PREFIX = "POS daily code:"


class POSRefundCode(Document):
	def validate(self):
		prepare_code(self)


@frappe.whitelist(methods=["POST"])
def generate_codes(count: int = 1, company: str | None = None, notes: str | None = None) -> dict:
	"""Generate multi-use refund access codes (see the shared helper)."""
	return generate_codes_for(CODE_DOCTYPE, count, company, notes)


@frappe.whitelist(methods=["POST"])
def generate_daily_code(company: str) -> dict:
	"""One refund code for an outlet manager to hand to a cashier: scoped to
	`company` (one the manager may act for) and valid today only."""
	from pos_next.api.purchase_orders import _assert_purchase_company
	from pos_next.utils.authz import is_management_user

	if not is_management_user():
		frappe.throw(_("Only POS Managers can generate refund codes"), frappe.PermissionError)
	_assert_purchase_company(company)

	# one live POS code per company: generating again retires the previous ones
	# (HQ-issued refund codes carry no marker and stay untouched)
	previous = frappe.get_all(
		CODE_DOCTYPE,
		filters=[
			[CODE_DOCTYPE, "status", "=", "Active"],
			[CODE_DOCTYPE, "notes", "like", f"{DAILY_NOTE_PREFIX}%"],
			["POS Discount Code Company", "company", "=", company],
		],
		pluck="name",
	)
	for name in previous:
		# managers hold create, not write, on this doctype
		frappe.db.set_value(CODE_DOCTYPE, name, "status", "Disabled")

	doc = frappe.get_doc(
		{
			"doctype": CODE_DOCTYPE,
			"status": "Active",
			"valid_from": today(),
			"valid_upto": today(),
			"company_scope": "Selected Outlets",
			"companies": [{"company": company}],
			"notes": f"{DAILY_NOTE_PREFIX} {frappe.session.user}",
		}
	).insert()  # code is generated by prepare_code; insert checks create permission
	return {"code": doc.code, "company": company, "valid_upto": doc.valid_upto}
