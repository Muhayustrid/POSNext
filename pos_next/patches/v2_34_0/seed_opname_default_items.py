def execute():
	parent = "POS Next Global Settings"
	# never overwrite a list someone already edited
	if frappe.db.exists(
		"POS Opname Default Item", {"parenttype": parent, "parentfield": "opname_default_items"}
	):
		return
	existing = set(frappe.get_all("Item", filters={"name": ("in", DEFAULT_ITEMS)}, pluck="name"))
	# codes missing on this site are skipped; add them in Global Settings later
	codes = [code for code in DEFAULT_ITEMS if code in existing]
	# rows are inserted directly: saving the single would rerun its on_update side effects
	for idx, code in enumerate(codes, 1):
		frappe.get_doc(
			{
				"doctype": "POS Opname Default Item",
				"parent": parent,
				"parenttype": parent,
				"parentfield": "opname_default_items",
				"idx": idx,
				"item_code": code,
				"item_name": frappe.db.get_value("Item", code, "item_name"),
			}
		).db_insert()
